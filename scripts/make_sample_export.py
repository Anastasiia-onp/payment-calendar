# -*- coding: utf-8 -*-
"""
Синтетическая выгрузка «из учётной системы» — для отладки импортёра.

Намеренно сделана неудобной, как реальные выгрузки:
  * шапка отчёта занимает первые строки, таблица начинается не с первой;
  * названия колонок свои, не совпадают с полями реестра;
  * суммы записаны текстом с пробелами и словом «руб.»;
  * часть дат — текстом, часть — датами;
  * есть пустые строки, строка «Итого» и строка без суммы.

Запуск:  python scripts/make_sample_export.py
"""

import os
from datetime import date, datetime

from openpyxl import Workbook
from openpyxl.styles import Font, Alignment

OUT_NAME = "Выгрузка_Счета_к_оплате_ДЕМО.xlsx"

# поставщик, документ, объект, срок оплаты, сумма, вид расхода, примечание
EXPORT_ROWS = [
    ("Подрядчик 3", "Счёт № 412 от 02.11.2026", "Объект 2 — БЦ, фасад",
     "24.11.2026", "840 000,00 руб.", "Подрядчики", "Пусконаладка"),
    ("Поставщик 4", "Счёт № 1177 от 05.11.2026", "Объект 1 — ТЦ, остекление",
     "27.11.2026", "415 300,50 руб.", "Материалы", "Уплотнитель, доставка"),
    ("Поставщик 2", "Счёт № 903 от 06.11.2026", "Объект 3 — склад, окна",
     datetime(2026, 12, 4), "1 120 000,00 руб.", "Материалы", ""),
    ("Подрядчик 2", "Акт № 56 от 10.11.2026", "Объект 3 — склад, окна",
     "11.12.2026", "365 000,00 руб.", "Подрядчики", "Дополнительные работы"),
    ("Сервис-центр", "Счёт № 88 от 12.11.2026", "Общие",
     "18.12.2026", "72 400,00 руб.", "Прочие расходы", "Обслуживание техники"),
    ("Поставщик 5", "Счёт № 240 от 16.11.2026", "Объект 2 — БЦ, фасад",
     datetime(2026, 12, 25), "690 000,00 руб.", "Материалы", "Герметик"),
    # строка без суммы — импортёр обязан её отбраковать, а не придумать число
    ("Подрядчик 4", "Счёт № 501 от 18.11.2026", "Объект 1 — ТЦ, остекление",
     "29.12.2026", None, "Подрядчики", "Сумма уточняется"),
    # дата отсутствует — тоже в замечания
    ("Поставщик 6", "Счёт № 77 от 19.11.2026", "Общие",
     None, "128 000,00 руб.", "Прочие расходы", "Срок не согласован"),
]


def main():
    base = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(base, "01_input")
    os.makedirs(out, exist_ok=True)
    path = os.path.join(out, OUT_NAME)

    wb = Workbook()
    ws = wb.active
    ws.title = "Отчёт"

    ws["A1"] = "ООО «Демо-компания»"
    ws["A1"].font = Font(bold=True, size=12)
    ws["A2"] = "Счета к оплате на период с 19.10.2026 по 17.01.2027"
    ws["A3"] = "Сформировано: " + date.today().strftime("%d.%m.%Y")

    headers = ["Поставщик", "Документ-основание", "Объект строительства",
               "Срок оплаты", "Сумма к оплате", "Вид расхода", "Примечание"]
    for i, name in enumerate(headers, start=1):
        c = ws.cell(row=5, column=i, value=name)
        c.font = Font(bold=True)
        c.alignment = Alignment(horizontal="center", wrap_text=True)

    row = 6
    for item in EXPORT_ROWS:
        for i, value in enumerate(item, start=1):
            ws.cell(row=row, column=i, value=value)
        row += 1

    row += 1  # пустая строка перед итогом
    ws.cell(row=row, column=1, value="Итого:").font = Font(bold=True)
    ws.cell(row=row, column=5, value="3 630 700,50 руб.").font = Font(bold=True)

    for col, width in zip("ABCDEFG", [22, 30, 28, 14, 18, 18, 26]):
        ws.column_dimensions[col].width = width

    wb.save(path)
    print("Создана выгрузка: " + OUT_NAME)
    print("Строк с данными: {n} (из них 2 заведомо неполные)".format(n=len(EXPORT_ROWS)))


if __name__ == "__main__":
    main()
